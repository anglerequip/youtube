"""Builds lure30.py from shed.py (shared set, characters, acting engine) plus the blocks for "The Lure Avalanche"."""
import os
D = os.path.dirname(os.path.abspath(__file__)); P = os.path.dirname(D)
L = open(os.path.join(P, 'shed.py'), encoding='utf-8').read().split('\n')
B = lambda n: open(os.path.join(D, n), encoding='utf-8').read().rstrip('\n').split('\n')
def find(prefix, start=0):
    for i in range(start, len(L)):
        if L[i].startswith(prefix): return i
    raise SystemExit('anchor not found: ' + prefix)
i_act = find('# ----------------------------------------------------------------------------------------------- cycle 9: big actions')
i_cam = find('# ----------------------------------------------------------------------------------------------- cameras + cuts')
i_cuts = find('cuts = [', i_cam); i_eo = find('def ease_out', i_cuts)
i_rack = find("    elif mv[0] == 'rack':", i_eo); i_mark = find('    m = sc.timeline_markers.new', i_rack)
i_beats = find('# beats from the script'); i_bl = find('BLINK = {w: [] for w in rig}')
i_src = find("    SRC = retarget.Source("); i_ms = find('    def mocap_state(who, t):'); i_mp = find('    def mocap_pose(who, t):')
i_set = find("                    pb_.rotation_quaternion = q_", i_mp)
i_min = find("    hands['minute'].rotation_euler")
out = (L[:i_act] + B('b1_props.py') + L[i_cam:i_cuts] + B('b2_cuts.py') + L[i_eo:i_mark] + B('b2b_whip.py') + L[i_mark:i_beats]
       + B('b3_acting.py') + L[i_bl:i_src]
       + ["    SRC = retarget.Source(kit.asset(r'D:\\CounterPhysical\\assets-cc0\\anim\\UAL1_Standard.glb'), [kit.asset(r'D:\\CounterPhysical\\assets-cc0\\anim\\UAL2_Standard.glb')])"]
       + L[i_src + 1:i_ms] + B('b4_mocap_state.py') + L[i_mp:i_set]
       + ["                    w_o = ovr(who, b_, t)", "                    pb_.rotation_quaternion = q_.slerp(pb_.rotation_quaternion.copy(), w_o) if w_o > 0 else q_"]
       + L[i_set + 1:i_min] + B('b5_frame_props.py') + L[i_min:])
s = '\n'.join(out)
s = s.replace('"""The fishing shed: Nils and Theo pick lures by reading the weather and the time (Caesar, 27 Nov).',
              '"""GENERATED by lure30_blocks/assemble.py from shed.py: "The Lure Avalanche" (30 s). Edit the blocks, not this file.\n\nThe fishing shed: Nils and Theo pick lures by reading the weather and the time (Caesar, 27 Nov).', 1)
s = s.replace("bpy.ops.wm.save_as_mainfile(filepath=os.path.join(OUT, 'shed.blend'))", "bpy.ops.wm.save_as_mainfile(filepath=os.path.join(OUT, 'lure30.blend'))")
open(os.path.join(P, 'lure30.py'), 'w', encoding='utf-8').write(s)
print('lure30.py', len(out), 'lines')
